//! The Lua side of the output (spec §2.2, §3.11; M4): `scripts/razdor/map_data.lua`, the generated
//! table the runtime reads, the `<name>.omwscripts` that registers the runtime, and the copies of the
//! fixed runtime scripts, which live in `crates/openmw-world/lua/` and are embedded with `include_str!`.

use crate::actors::{ArmyOut, BODY_SPACING};
use std::fmt::Write;

/// The fixed runtime, as (path under the output folder, text). The paths are the ones the
/// `.omwscripts` names.
pub const RUNTIME: [(&str, &str); 4] = [
    ("scripts/razdor/common.lua", include_str!("../lua/common.lua")),
    ("scripts/razdor/global.lua", include_str!("../lua/global.lua")),
    ("scripts/razdor/player.lua", include_str!("../lua/player.lua")),
    ("scripts/razdor/army.lua", include_str!("../lua/army.lua")),
];

/// The path of the generated table, relative to the output folder.
pub const MAP_DATA_PATH: &str = "scripts/razdor/map_data.lua";

/// A Lua string literal: the text in double quotes, with `\`, `"`, newlines, carriage returns and
/// every other control byte escaped (control bytes as three decimal digits, `\ddd`). Other bytes,
/// including the UTF-8 of Cyrillic, go through unchanged: a Lua string is bytes.
pub fn string(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            c if (c as u32) < 0x20 || c as u32 == 0x7f => {
                let _ = write!(out, "\\{:03}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The `.omwscripts` file that registers the runtime (spec §2.4).
pub fn omwscripts() -> String {
    "# Written by razdor-openmw: the Lua runtime of the converted map (spec 2.4).\n\
     GLOBAL: scripts/razdor/global.lua\n\
     PLAYER: scripts/razdor/player.lua\n\
     CUSTOM: scripts/razdor/army.lua\n"
        .to_string()
}

/// What `map_data.lua` holds besides the armies: the map, the passability rows and the start.
pub struct MapData<'a> {
    pub width: i64,
    pub height: i64,
    pub tile: i64,
    /// The on-foot values, row-major from the north (`passable::build`); 0 is closed.
    pub passable: &'a [u8],
    /// Building footprints in world units, `[x0, x1, y0, y1]`.
    pub boxes: &'a [[i64; 4]],
    pub armies: &'a [ArmyOut],
    /// The hero the player plays: archetype, start tile and the ground height at its centre.
    pub hero_archetype: &'a str,
    pub hero_tile: (i64, i64),
    pub hero_z: i64,
    /// The game time scale (spec §3.11, Q2).
    pub time_scale: i64,
    /// Whether the passability guard runs (`--no-guard` turns it off).
    pub guard: bool,
}

/// The `map_data.lua` text (deterministic: no tables are iterated in hash order).
pub fn map_data(d: &MapData) -> String {
    let mut s = String::new();
    s.push_str("-- Generated by razdor-openmw from the map's JSON. Do not edit.\nreturn {\n");
    let _ = writeln!(s, "  width = {}, height = {}, tile = {},", d.width, d.height, d.tile);
    let _ = writeln!(s, "  time_scale = {}, guard = {}, debug_tiles = false,", d.time_scale, d.guard);
    let _ = writeln!(
        s,
        "  start = {{ archetype = {}, tile = {{{}, {}}}, z = {} }},",
        string(d.hero_archetype),
        d.hero_tile.0,
        d.hero_tile.1,
        d.hero_z
    );

    // Passability rows: one hex digit per tile, row 0 the north row; 0 is closed. A value above 15
    // is written as 15, which is still open.
    s.push_str("  passable = {\n");
    let w = d.width as usize;
    for row in d.passable.chunks(w) {
        s.push_str("    \"");
        for &v in row {
            let _ = write!(s, "{:x}", v.min(15));
        }
        s.push_str("\",\n");
    }
    s.push_str("  },\n");

    s.push_str("  buildings = {\n");
    for b in d.boxes {
        let _ = writeln!(s, "    {{ x0 = {}, x1 = {}, y0 = {}, y1 = {} }},", b[0], b[1], b[2], b[3]);
    }
    s.push_str("  },\n");

    let _ = writeln!(s, "  spacing = {},", BODY_SPACING);
    s.push_str("  armies = {\n");
    for a in d.armies {
        let _ = writeln!(
            s,
            "    {{ id = {}, name = {}, faction = {}, relations = {{{}}}, hostile = {},",
            a.id,
            string(&a.name),
            a.faction,
            a.relations.iter().map(|r| r.to_string()).collect::<Vec<_>>().join(", "),
            a.hostile
        );
        let _ = writeln!(
            s,
            "      tile = {{{}, {}}}, spawn = {{x = {}, y = {}, z = {}}}, relocated = {}, ship = {},",
            a.tile.0, a.tile.1, a.spawn[0], a.spawn[1], a.spawn[2], a.relocated, a.ship
        );
        let _ = writeln!(
            s,
            "      inactive = {}, patrols = {}, patrol_radius = {}, behaviour = {}, home_building = {}, respawn_days = {},",
            a.inactive, a.patrols, a.patrol_radius, a.behaviour, a.home_building, a.respawn_days
        );
        s.push_str("      units = {");
        for (i, (record, count, leader)) in a.units.iter().enumerate() {
            if i > 0 {
                s.push_str(", ");
            }
            let _ = write!(s, "{{ record = {}, count = {}, leader = {} }}", string(record), count, leader);
        }
        s.push_str("} },\n");
    }
    s.push_str("  },\n}\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn strings_escape_quotes_backslashes_and_newlines() {
        assert_eq!(string(r#"a"b\c"#), r#""a\"b\\c""#);
        assert_eq!(string("x\ny\rz"), r#""x\ny\rz""#);
        assert_eq!(string("tab\there"), "\"tab\\009here\"");
    }

    #[test]
    fn cyrillic_passes_through_as_utf8() {
        // Lua reads the file as bytes: the UTF-8 of "Отряд" stays as it is, between the quotes.
        let text = "Отряд рыцаря";
        let lit = string(text);
        assert_eq!(lit, format!("\"{text}\""));
        assert!(lit.as_bytes().windows(2).any(|w| w == [0xD0, 0x9E]), "О is D0 9E in UTF-8");
    }

    #[test]
    fn the_runtime_scripts_are_embedded_and_named_by_the_omwscripts() {
        let script = omwscripts();
        for (path, text) in RUNTIME {
            assert!(!text.is_empty(), "{path} is empty");
        }
        // common.lua is a module that the three scripts require; only the scripts are registered.
        for path in ["scripts/razdor/global.lua", "scripts/razdor/player.lua", "scripts/razdor/army.lua"] {
            assert!(script.contains(path), "{path} is not in the .omwscripts");
        }
        assert!(!script.contains("common.lua"));
    }

    #[test]
    fn map_data_has_the_passability_rows_the_armies_and_the_escaped_names() {
        let armies = vec![ArmyOut {
            id: 1,
            name: "Отряд \"Раз\"\\".to_string(),
            faction: 2,
            relations: vec![-2, 0, 1, 3],
            hostile: true,
            tile: (1, 0),
            spawn: [1536, 3584, 0],
            relocated: true,
            ship: false,
            inactive: true,
            patrols: true,
            patrol_radius: 2,
            behaviour: 1,
            home_building: 0,
            respawn_days: 1,
            units: vec![("rz_army_1".to_string(), 1, true), ("rz_u4_l0".to_string(), 2, false)],
        }];
        // Row 0: closed, cost 1, cost 20 (a value above 15 is written as f, still open); row 1: 3, closed, 15.
        let passable = [0u8, 1, 20, 3, 0, 15];
        let boxes = [[1, 2, 3, 4]];
        let d = MapData {
            width: 3,
            height: 2,
            tile: 1024,
            passable: &passable,
            boxes: &boxes,
            armies: &armies,
            hero_archetype: "knight",
            hero_tile: (1, 0),
            hero_z: 96,
            time_scale: 120,
            guard: true,
        };
        let text = map_data(&d);
        assert!(text.contains("\"01f\",\n    \"30f\""), "{text}");
        assert!(text.contains(r#"name = "Отряд \"Раз\"\\""#), "{text}");
        assert!(text.contains("{ record = \"rz_u4_l0\", count = 2, leader = false }"), "{text}");
        assert!(text.contains("relations = {-2, 0, 1, 3}, hostile = true,"), "{text}");
        assert!(text.contains("spacing = 300,"), "{text}");
        assert!(text.contains("time_scale = 120, guard = true"), "{text}");
        assert!(text.contains("start = { archetype = \"knight\", tile = {1, 0}, z = 96 }"), "{text}");
        assert!(text.contains("{ x0 = 1, x1 = 2, y0 = 3, y1 = 4 }"), "{text}");
    }
}
