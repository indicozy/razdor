//! The `dt:` alias table: Latin names of Discord Times' units, items and spells, generated from
//! Razdor's English translations by `razdor-pack gen-aliases` and compiled in.

use std::collections::BTreeMap;
use std::sync::OnceLock;

use serde::Deserialize;

use super::refs::DtKind;

const TABLE: &str = include_str!("../../data/pack/dt-aliases.toml");

#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct Table {
    #[serde(default)]
    unit: BTreeMap<String, u32>,
    #[serde(default)]
    item: BTreeMap<String, u32>,
    #[serde(default)]
    spell: BTreeMap<String, u32>,
}

fn table() -> &'static Table {
    static TABLE_PARSED: OnceLock<Table> = OnceLock::new();
    TABLE_PARSED.get_or_init(|| toml::from_str(TABLE).expect("data/pack/dt-aliases.toml parses"))
}

fn section(kind: DtKind) -> &'static BTreeMap<String, u32> {
    let t = table();
    match kind {
        DtKind::Unit => &t.unit,
        DtKind::Item => &t.item,
        DtKind::Spell => &t.spell,
    }
}

/// The GlobalIndex (or spell position) of the base content named `alias`.
pub fn resolve(kind: DtKind, alias: &str) -> Option<u32> {
    section(kind).get(alias).copied()
}

/// Every alias of `kind`, sorted (the names a studio's combo box offers).
pub fn names(kind: DtKind) -> impl Iterator<Item = &'static str> {
    section(kind).keys().map(String::as_str)
}

/// Up to three aliases of `kind` closest to `alias` (edit distance at most 3), as references.
pub fn suggest(kind: DtKind, alias: &str) -> Vec<String> {
    let mut near: Vec<(usize, &str)> = section(kind)
        .keys()
        .map(|k| (distance(alias, k), k.as_str()))
        .filter(|(d, _)| *d <= 3)
        .collect();
    near.sort();
    near.into_iter()
        .take(3)
        .map(|(_, k)| match kind {
            DtKind::Unit => format!("dt:{k}"),
            _ => format!("dt:{}/{k}", kind.word()),
        })
        .collect()
}

/// The number of aliases of `kind` (for the generator's log and tests).
pub fn count(kind: DtKind) -> usize {
    section(kind).len()
}

/// The slug of an English name: lowercase ASCII letters and digits, every other run of
/// characters as one `_`, no `_` at the ends; `None` when nothing is left.
pub fn slugify(name: &str) -> Option<String> {
    let mut out = String::new();
    for c in name.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('_') {
            out.push('_');
        }
    }
    let t = out.trim_matches('_');
    (!t.is_empty()).then(|| t.to_string())
}

/// The result of [`generate`].
pub struct Generated {
    /// The TOML file's text.
    pub text: String,
    /// Units, items and spells in the table.
    pub counts: [usize; 3],
    /// Entries with no English name (their alias is `unit_<id>` and the like).
    pub unnamed: usize,
}

/// The alias table of the install `dt`: each name's English translation (Razdor's Eng files)
/// slugified, duplicates numbered `_2`, `_3` in id order. Names without a translation get
/// `<kind>_<id>`.
pub fn generate(dt: &crate::dt::install::DtInstall) -> Generated {
    let en = |ru: &str| dt.english.as_ref().and_then(|d| d.english(ru)).map(str::to_string);
    let mut unnamed = 0;
    let mut sections = Vec::new();
    // (GlobalIndex or position, English name when translated) per kind.
    type Entries = Vec<(u32, Option<String>)>;
    let sets: [(DtKind, Entries); 3] = [
        (DtKind::Unit, dt.units.iter().map(|u| (u.id, en(&u.name))).collect()),
        (DtKind::Item, dt.artefacts.iter().map(|a| (a.id, en(&a.name))).collect()),
        (DtKind::Spell, dt.spells.iter().map(|s| (s.id, en(&s.name))).collect()),
    ];
    for (kind, mut entries) in sets {
        entries.sort_by_key(|(id, _)| *id);
        let mut used = std::collections::BTreeSet::new();
        let mut lines = Vec::new();
        for (id, name) in &entries {
            let base = match name.as_deref().and_then(slugify) {
                Some(slug) => slug,
                None => {
                    unnamed += 1;
                    format!("{}_{id}", kind.word())
                }
            };
            let mut alias = base.clone();
            let mut n = 2;
            while used.contains(&alias) {
                alias = format!("{base}_{n}");
                n += 1;
            }
            used.insert(alias.clone());
            lines.push(format!("{alias} = {id}\n"));
        }
        sections.push((kind, lines, entries.len()));
    }
    let mut text = String::from(
        "# Latin aliases of Discord Times' content, for `dt:` references in packages\n\
         # (docs/reference/rzpack-format.md). Generated by `razdor-pack gen-aliases` from\n\
         # Razdor's English translations of the game files; do not edit by hand.\n\
         # A value is a unit's or item's GlobalIndex, or a spell's position in its file.\n",
    );
    let mut counts = [0; 3];
    for (k, (kind, lines, n)) in sections.iter().enumerate() {
        counts[k] = *n;
        text.push_str(&format!("\n[{}]\n", kind.word()));
        for l in lines {
            text.push_str(l);
        }
    }
    Generated { text, counts, unnamed }
}

/// Levenshtein distance over bytes (aliases are ASCII).
fn distance(a: &str, b: &str) -> usize {
    let b = b.as_bytes();
    let mut prev: Vec<usize> = (0..=b.len()).collect();
    for (i, ca) in a.bytes().enumerate() {
        let mut cur = vec![i + 1; b.len() + 1];
        for (j, &cb) in b.iter().enumerate() {
            let sub = prev[j] + usize::from(ca != cb);
            cur[j + 1] = sub.min(prev[j + 1] + 1).min(cur[j] + 1);
        }
        prev = cur;
    }
    prev[b.len()]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_has_every_kind() {
        assert!(count(DtKind::Unit) > 50);
        assert!(count(DtKind::Item) > 10);
        assert!(count(DtKind::Spell) > 10);
    }

    #[test]
    fn distance_is_levenshtein() {
        assert_eq!(distance("knight", "knight"), 0);
        assert_eq!(distance("knigth", "knight"), 2);
        assert_eq!(distance("", "abc"), 3);
        assert_eq!(distance("kitten", "sitting"), 3);
    }

    #[test]
    fn suggestions_are_close_and_prefixed() {
        let near = suggest(DtKind::Item, "relik");
        assert!(near.iter().all(|s| s.starts_with("dt:item/")));
        assert!(suggest(DtKind::Unit, "zzzzzzzzzzzzzzzz").is_empty());
    }
}
